export type UiKey = keyof typeof UI_DEFAULTS;

/** Dictionary map → translator: the phrase for `portal-<key>`, else the English default; `{name}` placeholders filled from `vars`. */
export function translator(dictionary: Record<string, unknown> | null | undefined) {
  return (key: UiKey, vars?: Record<string, string | number>): string => {
    const raw = dictionary?.[`portal-${key}`];
    // An entry without a phrase in this language comes back as its own key: use the default then.
    let text = typeof raw === "string" && raw.trim() && raw.trim() !== `portal-${key}` ? raw : UI_DEFAULTS[key];
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
    return text;
  };
}

/** next-intl messages ({ [site]: dictionary }) → one flat dictionary map. */
export function flattenMessages(messages: unknown): Record<string, unknown> {
  if (!messages || typeof messages !== "object") return {};
  const out: Record<string, unknown> = {};
  for (const v of Object.values(messages as Record<string, unknown>)) if (v && typeof v === "object") Object.assign(out, v);
  return out;
}
